// The classic script and self-contained worker both work from file://.
// Keep at most one in-flight job and the newest edit.
let worker = null;
let active = null;
let queued = null;
let nextId = 0;

function superseded() {
  return new DOMException("A newer text replaced this request.", "AbortError");
}

function resetWorker() {
  if (worker) worker.terminate();
  worker = null;
}

function finish(job, error, result) {
  if (active !== job) return;
  active = null;
  if (error) job.reject(error);
  else job.resolve(result);
  if (queued) {
    const next = queued;
    queued = null;
    start(next);
  }
}

function createWorker() {
  const program = new Blob(["(", initializeCounterWorker.toString(), ")()"], { type: "text/javascript" });
  const url = URL.createObjectURL(program);
  let instance;
  try {
    instance = new Worker(url);
  } finally {
    URL.revokeObjectURL(url);
  }
  instance.onmessage = ({ data }) => {
    if (instance !== worker || !active || data.id !== active.id) return;
    finish(active, data.error ? new Error(data.error) : null, data.result);
  };
  function fail() {
    if (instance !== worker) return;
    resetWorker();
    if (active) finish(active, new Error("The text counter worker could not complete the request."));
  }
  instance.onerror = fail;
  instance.onmessageerror = fail;
  return instance;
}

function start(job) {
  active = job;
  try {
    if (!worker) worker = createWorker();
    worker.postMessage({ id: job.id, text: job.text });
  } catch (error) {
    resetWorker();
    finish(job, error);
  }
}

function count(text) {
  if (typeof text !== "string") return Promise.reject(new TypeError("Expected plain text."));
  return new Promise((resolve, reject) => {
    const job = { id: ++nextId, text, resolve, reject };
    if (queued) {
      queued.reject(superseded());
      queued = null;
    }
    // A superseded large paste should not delay the next small edit.
    if (active && active.text.length >= 100000) {
      resetWorker();
      active.reject(superseded());
      active = null;
    }
    if (active) queued = job;
    else start(job);
  });
}

function cancel() {
  resetWorker();
  if (active) active.reject(superseded());
  if (queued) queued.reject(superseded());
  active = null;
  queued = null;
}

globalThis.CountEngine = Object.freeze({ count, cancel });
globalThis.addEventListener("pagehide", cancel);

