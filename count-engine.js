  const hardBreak = /[\u000a-\u000d\u0085\u2028\u2029]/u;
  const space = /[ \t\u00a0\u3000]/u;
  const wordDelimiter = /[\u2013\u2014\u2022]/u;
  const eastAsianUnit = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}\p{Script=Bopomofo}\u3001-\u303f\u3099-\u309c\u30a0\u30fb\u30fc\ufe10-\ufe19\ufe30-\ufe4f\uff01-\uff60\uff61-\uff9f\uffe0-\uffe6]/u;

  function count(text) {
    let words = 0;
    let characters = 0;
    let charactersWithSpaces = 0;
    let inWord = false;

    // Iteration by code point preserves supplementary Han letters and counts
    // the two regional indicators in a flag individually.
    for (const character of text) {
      if (hardBreak.test(character)) {
        inWord = false;
        continue;
      }

      charactersWithSpaces += 1;
      if (space.test(character)) {
        inWord = false;
        continue;
      }

      characters += 1;
      if (wordDelimiter.test(character)) {
        inWord = false;
      } else if (eastAsianUnit.test(character)) {
        words += 1;
        inWord = false;
      } else if (!inWord) {
        words += 1;
        inWord = true;
      }
    }

    return { words, characters, charactersWithSpaces };
  }

  globalThis.WordCounterCompat = Object.freeze({ count });
