    if (left === NUMBER && isLetter(right)) return false;
    if (beforeLeft === NUMBER && betweenNumbers(left) && right === NUMBER) return false;
    if (left === KATAKANA && right === KATAKANA) return false;
    if (right === CONNECTOR && (extendable(left) || left === CONNECTOR)) return false;
    if (left === CONNECTOR && extendable(right)) return false;
    if (left === REGIONAL && right === REGIONAL && regionalRun % 2 === 1) return false;

